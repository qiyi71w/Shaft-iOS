#!/usr/bin/env python3
"""Sync the Android image filter page (Pixiv-Shaft 2026-10-13 `4ba746c51`) into iOS.

Generates, from the Android sources:
  - Shaft-iOS/Localization/ImageFilterStrings.swift  (7 languages, Android wording verbatim)
  - Shaft-iOS/Filter/ImageFilterIcons.swift          (Material vectors the page draws)
  - LocalizedKey cases for the new strings
and registers the Filter sources + tests in the Xcode project.

Requires fontTools (same as sync-plaza-icons.py):
  python3 -m pip install fonttools
"""
from pathlib import Path
import hashlib
import json
import re
import sys
import xml.etree.ElementTree as ET

from fontTools.pens.recordingPen import RecordingPen
from fontTools.svgLib.path import parse_path

root = Path(__file__).resolve().parents[1]
android = (Path(sys.argv[1]) if len(sys.argv) > 1 else root.parent / "Pixiv-Shaft") / "app/src/main/res"
if not android.is_dir():
    raise SystemExit("Usage: sync-image-filter.py /path/to/Pixiv-Shaft")

# ── strings ──────────────────────────────────────────────────────────────
locales = {"en": "values-en", "zh-Hans": "values", "zh-Hant": "values-zh-rTW",
           "ja": "values-ja", "ko": "values-ko", "ru": "values-ru", "tr": "values-tr"}
# Shared Android strings the page uses, namespaced so they can't collide with iOS keys.
extras = {"now_loading": "imageFilterNowLoading", "retry": "imageFilterRetry", "share": "imageFilterShare",
          "save_image_failed": "imageFilterSaveFailed", "ugoira_frames_undo": "imageFilterUndo"}


def key(name):
    if name in extras:
        return extras[name]
    parts = name.split("_")
    return parts[0] + "".join(p[:1].upper() + p[1:] for p in parts[1:])


def read(directory):
    result = {}
    for file in sorted((android / directory).glob("*.xml")):
        for node in ET.parse(file).getroot().findall("string"):
            name = node.attrib["name"]
            if name == "image_filter" or name.startswith("image_filter_") or name in extras:
                value = "".join(node.itertext()).replace("\\n", "\n").replace("\\'", "'").replace('\\"', '"')
                # Every placeholder becomes %@: the iOS catalog formats with String arguments only.
                result[name] = re.sub(r"%(\d+\$)?[sd]", "%@", value)
    return result


base = read("values")
lines = ["// Generated by scripts/sync-image-filter.py from Pixiv-Shaft (image filter, 2026-10-13).",
         "import Foundation", "", "enum ImageFilterStrings {",
         "    static let table: [String: [LocalizedKey: String]] = ["]
for tag, directory in locales.items():
    entries = read(directory)
    missing = set(base) - set(entries)
    if missing:
        raise SystemExit(f"Missing strings in {directory}: {sorted(missing)}")
    lines.append(f'        "{tag}": [')
    for name in sorted(base):
        lines.append(f"            .{key(name)}: {json.dumps(entries[name], ensure_ascii=False)},")
    lines.append("        ],")
lines += ["    ]", "}", ""]
(root / "Shaft-iOS/Localization/ImageFilterStrings.swift").write_text("\n".join(lines))

enum_file = root / "Shaft-iOS/Localization/LocalizedKey.swift"
content = enum_file.read_text()
missing_keys = [key(name) for name in sorted(base) if not re.search(r"\b" + key(name) + r"\b", content)]
if missing_keys:
    at = content.rfind("}")
    content = content[:at] + "    // Android image filter (ImageFilterFragment)\n    case " + ", ".join(missing_keys) + "\n" + content[at:]
    enum_file.write_text(content)

# ── icons ────────────────────────────────────────────────────────────────
icons = {"photoFilter": "ic_photo_filter_24", "refresh": "ic_baseline_refresh_48", "share": "ic_share_black_24dp",
         "download": "ic_file_download_black_24dp", "check": "ic_check_24dp"}
ns = "{http://schemas.android.com/apk/res/android}"
out = ["// Generated from Android vector paths by scripts/sync-image-filter.py.", "import SwiftUI", "",
       "/// Material glyphs of the Android filter page, in their own viewport units.",
       "enum FilterGlyph {", "    case " + ", ".join(icons), "",
       "    /// Android `viewportWidth` × `viewportHeight` (the refresh glyph is 54 × 48dp, not square).",
       "    var viewport: CGSize {", "        switch self {"]
paths = []
for name, file in icons.items():
    tree = ET.parse(android / "drawable" / f"{file}.xml").getroot()
    vw, vh = float(tree.get(ns + "viewportWidth")), float(tree.get(ns + "viewportHeight"))
    out.append(f"        case .{name}: return CGSize(width: {vw:g}, height: {vh:g})")
    paths.append(f"        case .{name}:")
    for element in tree.iter("path"):
        pen = RecordingPen()
        parse_path(element.attrib[ns + "pathData"], pen)

        def pt(p):
            return f"CGPoint(x: {p[0]:.9g}, y: {p[1]:.9g})"

        for op, coords in pen.value:
            if op == "moveTo":
                s = f"p.move(to: {pt(coords[0])})"
            elif op == "lineTo":
                s = f"p.addLine(to: {pt(coords[0])})"
            elif op == "curveTo":
                s = f"p.addCurve(to: {pt(coords[2])}, control1: {pt(coords[0])}, control2: {pt(coords[1])})"
            elif op == "qCurveTo":
                s = f"p.addQuadCurve(to: {pt(coords[1])}, control: {pt(coords[0])})"
            elif op == "closePath":
                s = "p.closeSubpath()"
            elif op == "endPath":
                continue
            else:
                raise ValueError(op)
            paths.append("            " + s)
out += ["        }", "    }", "", "    var path: Path {", "        var p = Path()", "        switch self {"]
out += paths
out += ["        }", "        return p", "    }", "}", "", '''/// Draws a glyph the way an Android `ImageView` (FIT_CENTER) draws its vector: scaled to fit the
/// frame, centred, filled with the foreground style.
struct FilterIcon: View {
    var glyph: FilterGlyph
    var body: some View {
        Canvas { context, bounds in
            let vp = glyph.viewport
            let s = min(bounds.width / vp.width, bounds.height / vp.height)
            context.translateBy(x: (bounds.width - vp.width * s) / 2, y: (bounds.height - vp.height * s) / 2)
            context.scaleBy(x: s, y: s)
            context.fill(glyph.path, with: .foreground)
        }
        .accessibilityHidden(true)
    }
}''', ""]
(root / "Shaft-iOS/Filter/ImageFilterIcons.swift").write_text("\n".join(out))

# ── Xcode project ────────────────────────────────────────────────────────
project = root / "Shaft-iOS.xcodeproj/project.pbxproj"
original = project.read_text()
content = original
sources = [str(p.relative_to(root / "Shaft-iOS")) for p in sorted((root / "Shaft-iOS/Filter").glob("*.swift"))]
sources.append("Localization/ImageFilterStrings.swift")
tests = [p.name for p in sorted((root / "Shaft-iOSTests").glob("ImageFilter*.swift"))]


def insert(marker, value):
    global content
    if content.count(marker) != 1:
        raise SystemExit(f"Ambiguous project marker: {marker}")
    content = content.replace(marker, marker + value, 1)


for path, test in [(p, False) for p in sources] + [(p, True) for p in tests]:
    name = Path(path).name
    rel = f"Shaft-iOSTests/{path}" if test else path
    fid = hashlib.sha256(f"image-filter:file:{rel}".encode()).hexdigest()[:24].upper()
    bid = hashlib.sha256(f"image-filter:build:{rel}".encode()).hexdigest()[:24].upper()
    if fid in content:
        continue
    insert("/* Begin PBXFileReference section */\n",
           f'\t\t{fid} /* {name} */ = {{isa = PBXFileReference; lastKnownFileType = sourcecode.swift; path = "{rel}"; sourceTree = "<group>"; }};\n')
    insert("/* Begin PBXBuildFile section */\n", f"\t\t{bid} /* {name} */ = {{isa = PBXBuildFile; fileRef = {fid}; }};\n")
    group = r"A1000000000000000000G001 = \{" if test else r"A1000000000000000000G002 /\* Shaft-iOS \*/ = \{"
    match = re.search(group + r"\s*isa = PBXGroup;\s*children = \(\n", content)
    if not match:
        raise SystemExit("Missing source group")
    insert(match.group(), f"\t\t\t\t{fid} /* {name} */,\n")
    if test:
        match = re.search(r"715CEB466C368648489445F5 = \{isa = PBXSourcesBuildPhase; buildActionMask = [^;]+; files = \(", content)
        insert(match.group(), bid + ",")
    else:
        match = re.search(r"/\* Begin PBXSourcesBuildPhase section \*/\s*[^\n]+\{\s*isa = PBXSourcesBuildPhase;\s*buildActionMask = [^;]+;\s*files = \(\n", content)
        insert(match.group(), f"\t\t\t\t{bid} /* {name} */,\n")
# Golden fixture folder (cases + Android-rendered hashes) → test bundle resources, like PlazaFixtures.
rel = "Shaft-iOSTests/ImageFilterFixtures"
fid = hashlib.sha256(f"image-filter:file:{rel}".encode()).hexdigest()[:24].upper()
bid = hashlib.sha256(f"image-filter:build:{rel}".encode()).hexdigest()[:24].upper()
if (root / rel).is_dir() and fid not in content:
    insert("/* Begin PBXFileReference section */\n",
           f'\t\t{fid} /* ImageFilterFixtures */ = {{isa = PBXFileReference; lastKnownFileType = folder; path = "{rel}"; sourceTree = "<group>"; }};\n')
    insert("/* Begin PBXBuildFile section */\n", f"\t\t{bid} /* ImageFilterFixtures */ = {{isa = PBXBuildFile; fileRef = {fid}; }};\n")
    match = re.search(r"A1000000000000000000G001 = \{\s*isa = PBXGroup;\s*children = \(\n", content)
    insert(match.group(), f"\t\t\t\t{fid} /* ImageFilterFixtures */,\n")
    # The test target's resources phase is the one that already carries PlazaFixtures.
    plaza = re.search(r"(\w{24}) /\* PlazaFixtures \*/ = \{isa = PBXBuildFile", content).group(1)
    match = re.search(r"\w{24} = \{isa = PBXResourcesBuildPhase; buildActionMask = [^;]+; files = \((?=[^)]*" + plaza + ")", content)
    insert(match.group(), bid + ",")
if project.read_text() != original:
    raise SystemExit("Project changed concurrently; retry.")
project.write_text(content)
print(f"Synced {len(base)} strings × {len(locales)} languages, {len(icons)} glyphs, {len(sources)} sources, {len(tests)} tests.")
